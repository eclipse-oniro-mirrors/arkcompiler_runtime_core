"""Generate a deterministic C++ header containing the offline Web frontend."""

import argparse
import json
from pathlib import Path


def cpp_string(value: str) -> str:
    chunks = [value[index:index + 100] for index in range(0, len(value), 100)] or [""]
    return "\n            ".join(json.dumps(chunk, ensure_ascii=True) for chunk in chunks)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", required=True)
    parser.add_argument("--asset", action="append", nargs=3, metavar=("ROUTE", "MIME", "FILE"), default=[])
    arguments = parser.parse_args()

    entries = []
    for route, mime, source in arguments.asset:
        content = Path(source).read_text(encoding="utf-8")
        entries.append(
            "        EmbeddedWebAsset{%s, %s,\n            %s},"
            % (cpp_string(route), cpp_string(mime), cpp_string(content))
        )

    output = """// Generated by embed_web_assets.py. Do not edit.
#ifndef BYTECODE_EXPLORER_WEB_ASSETS_GEN_H
#define BYTECODE_EXPLORER_WEB_ASSETS_GEN_H

#include \"web/assets/web_assets.h\"

#include <array>

namespace panda::bytecode_explorer {

inline constexpr std::array<EmbeddedWebAsset, %d> EMBEDDED_WEB_ASSETS {{
%s
}};

}  // namespace panda::bytecode_explorer

#endif  // BYTECODE_EXPLORER_WEB_ASSETS_GEN_H
""" % (len(entries), "\n".join(entries))

    output_path = Path(arguments.output)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, "w", encoding="utf-8", newline="\n") as output_handle:
        output_handle.write(output)


if __name__ == "__main__":
    main()
